// Regenerates src/lib/utils/wordFreq.ts — the frequency-ranked English
// wordlist behind the fuzzy autocorrect layer (autocorrect.ts).
//   - source ranking: Norvig count_1w.txt (Google Web Trillion Word Corpus)
//   - kept only if ALSO a real dictionary word (words_alpha.txt) — the corpus
//     itself contains popular misspellings ("teh") that must never rank
//   - never a known misspelling key from the typo dictionary
//   - top KEEP words, frequency order preserved (rank = line index)
// Inputs (download first):
//   %TEMP%/count_1w.txt     https://norvig.com/ngrams/count_1w.txt
//   %TEMP%/words_alpha.txt  https://raw.githubusercontent.com/dwyl/english-words/master/words_alpha.txt
// Run: node scripts/gen-word-freq.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const KEEP = 50000;

const tmp = process.env.TEMP ?? process.env.TMP;
const dict = new Set(
  readFileSync(join(tmp, "words_alpha.txt"), "utf8")
    .split(/\r?\n/)
    .map((w) => w.trim().toLowerCase())
    .filter(Boolean),
);

const here = dirname(fileURLToPath(import.meta.url));
const typoSrc = readFileSync(join(here, "..", "src", "lib", "utils", "typoData.ts"), "utf8");
const typoKeys = new Set([...typoSrc.matchAll(/^([a-z'][a-z']*):/gm)].map((m) => m[1]));

const out = [];
let skippedNonDict = 0, skippedTypo = 0;
for (const line of readFileSync(join(tmp, "count_1w.txt"), "utf8").split(/\r?\n/)) {
  if (out.length >= KEEP) break;
  const word = line.split("\t")[0]?.trim();
  if (!word || !/^[a-z]{2,}$/.test(word)) continue;
  if (!dict.has(word)) { skippedNonDict++; continue; }
  if (typoKeys.has(word)) { skippedTypo++; continue; }
  out.push(word);
}

const body = out.join("\n");
const file = `// GENERATED by scripts/gen-word-freq.mjs — do not hand-edit.
// Top ${out.length} English words by web frequency (Norvig count_1w),
// dictionary-validated (words_alpha) and typo-key-free. Frequency order —
// line index IS the rank; parsed in autocorrect.ts.
export const WORD_FREQ = \`${body}\`;
`;
writeFileSync(join(here, "..", "src", "lib", "utils", "wordFreq.ts"), file);
console.log(`kept=${out.length} skippedNonDict=${skippedNonDict} skippedTypo=${skippedTypo}`);
