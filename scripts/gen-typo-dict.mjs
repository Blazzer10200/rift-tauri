// Regenerates src/lib/utils/typoData.ts from the machine-readable
// Wikipedia common-misspellings list, filtered for high confidence:
//   - single unambiguous correction only (multi-suggestion lines dropped)
//   - misspelling must NOT itself be a valid English word (words_alpha.txt)
//   - clean shapes only: key = letters/apostrophes, value = letters/space/'/-
// Inputs (download first):
//   %TEMP%/misspellings_raw.txt  https://en.wikipedia.org/w/index.php?title=Wikipedia:Lists_of_common_misspellings/For_machines&action=raw
//   %TEMP%/words_alpha.txt       https://raw.githubusercontent.com/dwyl/english-words/master/words_alpha.txt
// Run: node scripts/gen-typo-dict.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const tmp = process.env.TEMP ?? process.env.TMP;
const raw = readFileSync(join(tmp, "misspellings_raw.txt"), "utf8");
const words = new Set(
  readFileSync(join(tmp, "words_alpha.txt"), "utf8")
    .split(/\r?\n/)
    .map((w) => w.trim().toLowerCase())
    .filter(Boolean),
);

const entries = new Map();
const conflicts = new Set();
let multi = 0, badShape = 0, validWord = 0;

for (const line of raw.split(/\r?\n/)) {
  const m = /^\s*([^\s>]+)->(.+)$/.exec(line);
  if (!m) continue;
  const key = m[1].trim().toLowerCase();
  const val = m[2].trim();
  if (val.includes(",")) { multi++; continue; }
  if (!/^[a-z][a-z']+$/.test(key) || !/^[A-Za-z][A-Za-z' -]*$/.test(val)) { badShape++; continue; }
  if (key === val.toLowerCase()) continue;
  if (words.has(key)) { validWord++; continue; }
  const prev = entries.get(key);
  if (prev !== undefined && prev !== val) { conflicts.add(key); continue; }
  entries.set(key, val);
}
for (const k of conflicts) entries.delete(k);

const sorted = [...entries.entries()].sort(([a], [b]) => (a < b ? -1 : 1));
const body = sorted.map(([k, v]) => `${k}:${v}`).join("\n");

const out = `// GENERATED by scripts/gen-typo-dict.mjs — do not hand-edit.
// Source: Wikipedia:Lists of common misspellings (For machines), filtered to
// unambiguous corrections whose misspelling is not a valid English word.
// Format: one "misspelling:correction" per line; parsed in autocorrect.ts.
export const TYPO_DATA = \`${body}\`;
`;

const here = dirname(fileURLToPath(import.meta.url));
writeFileSync(join(here, "..", "src", "lib", "utils", "typoData.ts"), out);
console.log(`kept=${sorted.length} multi=${multi} badShape=${badShape} validWord=${validWord} conflicts=${conflicts.size}`);
